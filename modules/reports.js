/**
 * GAITMATRIX / OA-Sense - Screening Report Generator Module
 * Clinical Referral Decision Support & Printable Documentation
 * 
 * Generates structured, professional medical-AI research screening summaries.
 * Employs cautious, referral-oriented clinical language:
 * - "Screening pattern suggests further clinical evaluation may be appropriate."
 * - Never claims definitive diagnosis.
 */

export class ReportGenerator {
    constructor() {}

    /**
     * Generate HTML and data object for a complete screening session
     * @param {object} sessionData - Session intake, features, inference, segmentation, and quality
     */
    generateReport(sessionData) {
        const {
            sessionInfo,
            patientContext,
            features,
            inference,
            segmentation,
            quality
        } = sessionData;

        const dateStr = new Date().toLocaleString();
        const category = inference ? inference.screeningCategory : 'NOT COMPUTED';
        const confidence = inference ? inference.confidence : 0;
        const modelName = inference ? inference.selectedModel : 'Ensemble (RF+GB)';
        const modelVersion = inference ? inference.modelVersion : 'GM-v0.1';

        // Clinical Referral Language Logic
        let referralRecommendation = '';
        let clinicalSummary = '';
        let riskBadgeClass = 'risk-low';

        if (category === 'ELEVATED') {
            riskBadgeClass = 'risk-elevated';
            referralRecommendation = 'RECOMMENDATION: Screening pattern demonstrates significant kinematic asymmetry and reduced sagittal joint excursions. Further clinical evaluation and musculoskeletal radiographic examination (e.g. weight-bearing radiographs) are advised.';
            clinicalSummary = 'Observed notable reduction in sagittal knee flexion ROM during swing phase, combined with marked lateral-to-medial plantar loading redistribution and reported functional stiffness.';
        } else if (category === 'MODERATE') {
            riskBadgeClass = 'risk-moderate';
            referralRecommendation = 'RECOMMENDATION: Screening pattern shows mild movement irregularities and moderate symptom report. Recommend clinical follow-up, physical therapy assessment, and longitudinal gait monitoring.';
            clinicalSummary = 'Observed mild kinematic asymmetry between bilateral limbs with moderate compensatory plantar load shifting and moderate reported joint discomfort.';
        } else {
            riskBadgeClass = 'risk-low';
            referralRecommendation = 'RECOMMENDATION: Biomechanical indicators and temporal parameters are within typical normative ranges. Routine physical activity and standard preventive joint care encouraged.';
            clinicalSummary = 'Symmetric bilateral knee range of motion, normal stance/swing cycle partitioning, and balanced plantar loading profile observed.';
        }

        const reportData = {
            reportId: `REP-${sessionInfo.sessionId}-${Date.now().toString().slice(-4)}`,
            generatedAt: dateStr,
            sessionId: sessionInfo.sessionId,
            patientContext,
            screeningCategory: category,
            confidence: `${confidence}%`,
            riskBadgeClass,
            modelName,
            modelVersion,
            datasetVersion: inference ? inference.datasetVersion : 'DS-SYNTH-v1.0',
            clinicalSummary,
            referralRecommendation,
            metrics: {
                kneeRom: `${features.featureDict.knee_rom}°`,
                kneeVelocity: `${features.featureDict.knee_velocity}°/s`,
                cadence: `${features.featureDict.cadence} steps/min`,
                gaitAsymmetry: `${(features.featureDict.gait_asymmetry * 100).toFixed(1)}%`,
                loadingAsymmetry: `${(features.featureDict.loading_asymmetry * 100).toFixed(1)}%`,
                heelLoading: `${(features.featureDict.heel_loading * 100).toFixed(1)}%`,
                forefootLoading: `${(features.featureDict.forefoot_loading * 100).toFixed(1)}%`,
                postureLean: `${features.featureDict.posture_lean}°`
            },
            temporal: segmentation ? segmentation.temporalSummary : {},
            explainabilityTop: inference && inference.explainability ? inference.explainability.topContributors : [],
            qualityStatus: quality ? quality.status : 'PASS',
            legalDisclaimer: 'RESEARCH PROTOTYPE NOTICE: This screening report is generated by an experimental AI research workstation for clinical referral decision support. It is NOT a medical diagnosis, does not replace licensed medical judgment, and has not received regulatory clearance. All calculations are based on synthetic demonstration data.'
        };

        return reportData;
    }

    /**
     * Trigger browser print dialog for the report
     */
    printReport() {
        window.print();
    }
}
